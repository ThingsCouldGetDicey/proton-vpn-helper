#!/usr/bin/env python3
"""Real Chromium routing test with three ephemeral *local* HTTPS proxy listeners.

Uses actual PAC cases generated by source/js/siteRouter/pac.ts. Each listener
records only its assigned synthetic test destination, never website content.
No Proton account, live VPN credentials, or public web browsing is required.
"""
import json
import os
import requests
import socket
import socketserver
import ssl
import subprocess
import tempfile
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

class ProxyHandler(socketserver.BaseRequestHandler):
    def handle(self):
        self.request.settimeout(4)
        try:
            raw = self.request.recv(8192)
            first = raw.split(b'\r\n', 1)[0].decode('ascii', 'replace')
            with self.server.record_lock:
                self.server.records.append(first)
            self.request.sendall(b'HTTP/1.1 502 Bad Gateway\r\nContent-Length: 0\r\nConnection: close\r\n\r\n')
        except (ssl.SSLError, OSError):
            pass

class ProxyServer(socketserver.ThreadingMixIn, socketserver.TCPServer):
    allow_reuse_address = True
    daemon_threads = True
    def __init__(self, context):
        super().__init__(('127.0.0.1', 0), ProxyHandler)
        self.context = context
        self.records = []
        self.record_lock = threading.Lock()
    def get_request(self):
        socket_obj, addr = super().get_request()
        try:
            return self.context.wrap_socket(socket_obj, server_side=True), addr
        except (ssl.SSLError, OSError):
            socket_obj.close()
            raise

def main():
    with tempfile.TemporaryDirectory(prefix='helper-pac-transport-') as directory:
        td = Path(directory)
        cert, key = td/'test.crt', td/'test.key'
        subprocess.run(['openssl','req','-x509','-newkey','rsa:2048','-sha256',
            '-days','1','-nodes','-keyout',str(key),'-out',str(cert),
            '-subj','/CN=localhost'],check=True,capture_output=True)
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(certfile=str(cert),keyfile=str(key))
        hosts = {label:ProxyServer(context) for label in ('CH','NL','DEFAULT')}
        for proxy in hosts.values():
            threading.Thread(target=proxy.serve_forever, daemon=True).start()
        ports = [str(hosts[label].server_address[1]) for label in ('CH','NL','DEFAULT')]
        env = os.environ.copy()
        env['TS_NODE_SKIP_PROJECT']='1'
        env['TS_NODE_COMPILER_OPTIONS']=json.dumps({
            'module':'Node16','moduleResolution':'Node16','target':'ES2020',
            'rootDir':'.','ignoreDeprecations':'6.0'})
        command=['node',str(ROOT/'node_modules/.bin/ts-node'),
                 str(ROOT/'tests/emit_pac_fixture.ts'),*ports]
        pac=subprocess.run(command,cwd=ROOT,env=env,text=True,
                           capture_output=True,timeout=18,check=True).stdout
        assert 'FindProxyForURL' in pac
        assert 'HTTPS 127.0.0.1:9' in pac
        assert 'DIRECT' not in pac, 'No fallback to DIRECT in this synthetic fixture'
        # Must never directly access fake internet sites if the PAC is invalid.
        profile=td/'chromium-profile'
        driver_port=19349
        endpoint=f'http://127.0.0.1:{driver_port}'
        driver=subprocess.Popen(['chromedriver',f'--port={driver_port}',
            '--allowed-ips=127.0.0.1','--log-level=SEVERE'],
            stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        sid=None
        try:
            for _ in range(65):
                try:
                    if requests.get(endpoint+'/status',timeout=.5).status_code==200:
                        break
                except requests.RequestException:
                    pass
                time.sleep(.15)
            else:
                raise RuntimeError('ChromeDriver not ready')
            options={'binary':'/usr/bin/chromium','args':[
                '--headless=new','--no-sandbox','--disable-gpu',
                '--disable-dev-shm-usage','--disable-quic',
                '--ignore-certificate-errors','--disable-background-networking',
                '--no-first-run','--no-default-browser-check',
                '--user-data-dir='+str(profile),
                '--load-extension='+str(ROOT/'distribution'),
                '--disable-extensions-except='+str(ROOT/'distribution')
            ]}
            response=requests.post(endpoint+'/session',json={
                'capabilities':{'alwaysMatch':{
                    'browserName':'chrome','goog:chromeOptions':options,
                    'pageLoadStrategy':'none'
                }}},timeout=35)
            if response.status_code >= 400:
                raise RuntimeError('ChromeDriver session refused: '+response.text[:1800])
            response.raise_for_status()
            data=response.json()
            if data.get('value',{}).get('error'):
                raise RuntimeError(str(data))
            sid=data['value'].get('sessionId') or data.get('sessionId')
            assert sid
            wd_endpoint=endpoint+'/session/'+sid
            def wd(method,path,payload=None):
                res=requests.request(method,wd_endpoint+path,json=payload,timeout=18)
                res.raise_for_status()
                value=res.json()['value']
                if isinstance(value,dict) and value.get('error'):
                    raise RuntimeError(str(value))
                return value
            def js(source,*args):
                return wd('POST','/execute/sync',{'script':source,'args':args})
            extid=(ROOT/'native/extension_id.txt').read_text().strip()
            wd('POST','/url',{'url':f'chrome-extension://{extid}/site-router.html'})
            for _ in range(45):
                if js("return !!document.querySelector('#add-rule')"):
                    break
                time.sleep(.15)
            else:
                raise RuntimeError('Options page not available')
            time.sleep(1.5)
            status=js("""return chrome.proxy.settings.set({
                    value:{mode:'pac_script',pacScript:{data:arguments[0],mandatory:true}},
                    scope:'regular'
                }).then(()=>chrome.proxy.settings.get({})).then(
                    state=>({control:state.levelOfControl,mode:state.value?.mode,
                        mandatory:state.value?.pacScript?.mandatory||false})
                )""",pac)
            assert status['control']=='controlled_by_this_extension',status
            assert status['mode']=='pac_script',status
            print('PASS actual Chromium proxy settings owned by installed helper')
            cases={
                'CH':'https://first.example.com/helper-test-one',
                'NL':'https://second.example.com/helper-test-two',
                'DEFAULT':'https://unassigned.example.com/helper-test-default',
            }
            for dest in cases.values():
                js("return chrome.tabs.create({url:arguments[0]}).then(x=>!!x)",dest)
            js("return chrome.tabs.create({url:arguments[0]}).then(x=>!!x)",
               "https://blocked.example.com/helper-test-unavailable")
            for _ in range(85):
                found={}
                for label,server in hosts.items():
                    with server.record_lock:
                        raw=list(server.records)
                    found[label]=raw
                if (any('first.example.com' in v for v in found['CH']) and
                    any('second.example.com' in v for v in found['NL']) and
                    any('unassigned.example.com' in v for v in found['DEFAULT'])):
                    break
                time.sleep(.2)
            else:
                raise AssertionError('Chrome did not reach all intended TLS proxies: '+str(found))
            for label,domain in [('CH','first.example.com'),
                                 ('NL','second.example.com'),
                                 ('DEFAULT','unassigned.example.com')]:
                assert any(domain in v for v in found[label]),(label,found)
                print('PASS browser routed',domain,'to the',label,'local TLS proxy')
            for label,raw in found.items():
                for other in ['first.example.com','second.example.com','unassigned.example.com']:
                    if other not in cases[label]:
                        assert not any(other in line for line in raw),(label,other,raw)
            print('PASS no cross-country misrouting in synthetic Chromium traffic')
            time.sleep(.8)
            for label, server in hosts.items():
                with server.record_lock:
                    assert not any('blocked.example.com' in line for line in server.records), label
            print('PASS unavailable country never used another test proxy as fallback')
        finally:
            if sid:
                try:
                    requests.delete(endpoint+'/session/'+sid,timeout=5)
                except requests.RequestException:
                    pass
            driver.terminate()
            try: driver.wait(timeout=5)
            except subprocess.TimeoutExpired: driver.kill()
            for srv in hosts.values():
                srv.shutdown()
                srv.server_close()
if __name__=='__main__':
    main()
